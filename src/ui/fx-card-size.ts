/**
 * **特效几何常量的单一出处**（G2 修正 **R9-1** 新增；**值一字未改**）。
 *
 * ## 为什么需要它
 *
 * R9-1 的最后一颗要求是"**逐条判断写死的落点系数是否与卡/协议尺寸成比例**"。盘点时发现：
 * `fx-gen2.ts` 与 `effects/index.ts` 里有 **9 处**把"整卡浮层的左上角"写成
 * `${落点.x - 65}px` / `${落点.y - 89.4}px`，并把盒尺寸写成 `'130px'` / `'178.8px'`
 * —— 它们是同一个东西（**手牌/浮层卡的半个宽高**），却散在 9 个地方各写一遍。
 * 本波**不改这些数值**（见下），但必须先把"它们是什么"从"看起来像魔数"变成**可点名的常量**：
 *  · 评审与后续轮次可以一眼看出"这些数跟 `--card-h` 无关"（从而不会被"等比缩放"顺手改掉）；
 *  · 也避免下一次有人把其中一处改成 64 而没人发现（副本越多，漂移越静默）。
 *
 * ## 为什么这些数**不**跟随 R9-1 的 `--card-h`（140）
 *
 * `--card-h` 管的是**场上链路里的卡**（`.net-lane-band .stack .card`）与协议 holder；
 * 而这里的是**手牌卡 / 飞行浮层卡**——它的宽度由 `styles.css` 的 `.card { width: 130px }`
 * 决定，**本波一个字未改**（用户的第三次反馈只说"双方卡牌"与"链路/7 张/特效"，
 * 手牌仍然是热座页那一套 130px 扇形）。所以：
 *   · 浮层盒的半个宽高 = `65 / 89.4`（= 130/2、178.8/2）；
 *   · `178.8px` = 130px 卡宽的内容高（122 × 1.4）+ 8px 内边距/边框，`styles.css:410` 有推导。
 * 一旦将来手牌卡也缩放，**只改这里**即可（而不是去 9 个落点里逐个找 65）。
 *
 * ⚠️ **诚实边界**：这些常量描述的是"盒的尺寸与居中偏移"，不是"落点该在哪"。
 * `65 / 89.4` 是**手工居中**的写法（等价于 `落点 − 盒尺寸/2`），与 `HAND_END_LEAD` 那类
 * "让开多少"的观感量是两件不同的事（后者在 `./fx-seat` 里，且本波也不缩）。
 */

/** 手牌卡（= 浮层卡）的整卡宽（`styles.css` 的 `.card { width: 130px }`；本波未缩）。 */
export const HAND_CARD_W = 130;

/** 手牌卡的整卡高（= 122px 内容高 × 1.4 + 8px 内边距/边框；见 `styles.css:410` 的推导）。 */
export const HAND_CARD_H = 178.8;

/** 整卡盒的**半宽**：把浮层盒水平居中到落点用的手工偏移。 */
export const HAND_CARD_HALF_W = HAND_CARD_W / 2;      // 65

/** 整卡盒的**半高**：把浮层盒垂直居中到落点用的手工偏移。 */
export const HAND_CARD_HALF_H = HAND_CARD_H / 2;      // 89.4
